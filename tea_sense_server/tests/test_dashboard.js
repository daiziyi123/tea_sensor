"use strict";
const assert=require("node:assert/strict");
const {chooseDevice,freshness,displayReading,chartSegments,windowInfo,uniqueReadings}=require("../web/app.js");
const row=(id,time,status="OK",value=0)=>({id,device_id:"demo_h743_001",received_at:new Date(time).toISOString(),status,adc_raw:status==="OK"?0:null,moisture_pct:status==="OK"?value:null});
assert.equal(chooseDevice([{device_id:"demo_h743_001"}]),"tea_h743_001");
assert.equal(chooseDevice([{device_id:"demo_h743_001"},{device_id:"tea_h743_001"}]),"tea_h743_001");
assert.equal(chooseDevice([{device_id:"tea_h743_001"}],"demo_h743_001",true),"demo_h743_001");
assert.equal(displayReading(row(1,1000)).moisture,"0.00");
assert.equal(displayReading(row(2,2000,"ADC_POLL_FAILED",50)).moisture,"—");
assert.equal(freshness(row(1,1000),61000,60).fresh,true);
assert.equal(freshness(row(1,1000),61001,60).fresh,false);
assert.equal(freshness(row(1,1000),2000,60,true).text,"数据未刷新 · 历史最后值");
const records=[row(1,1000),row(2,2000,"ADC_POLL_FAILED"),row(3,3000),row(4,90000),{...row(5,91000),device_id:"demo_other"}];
assert.deepEqual(chartSegments(records,"demo_h743_001",60000).map(segment=>segment.map(r=>r.id)),[[1],[3],[4]]);
console.log("PASS: real/demo selection, valid zero, latest failure, freshness boundary/API failure, per-device chart and gaps");
const windowRow={...row(20,3000,"OK",50),window_ms:3000,sample_count:30,valid_count:30,used_count:28};
assert.equal(windowInfo(windowRow).label,"土壤湿度");
assert.equal(windowInfo(windowRow).quality,"测量有效");
assert.equal(windowInfo(windowRow).counts,undefined);
const partial={...windowRow,valid_count:24,used_count:22,last_sample_error:"ADC_POLL_FAILED",cleanup_error_count:1};
assert.equal(windowInfo(partial).quality,"测量有效");
assert.equal(windowInfo(partial).counts,undefined);
assert.equal(windowInfo(partial).warning,false);
const insufficient={...windowRow,status:"WINDOW_INSUFFICIENT",valid_count:23,used_count:0,adc_raw:null,moisture_pct:null};
assert.equal(windowInfo(insufficient).quality,"样本不足");
assert.equal(displayReading(insufficient).moisture,"—");
assert.equal(windowInfo(row(21,1000)).label,"土壤湿度");
assert.deepEqual(uniqueReadings([windowRow,windowRow,partial]).map(r=>r.id),[20]);
assert.equal(chartSegments([windowRow,windowRow],"demo_h743_001",60000)[0].length,1);
const stream=[windowRow,{...windowRow,id:21,received_at:new Date(6000).toISOString()},
  {...insufficient,id:22,received_at:new Date(9000).toISOString()},
  {...windowRow,id:23,received_at:new Date(12000).toISOString()}];
assert.deepEqual(chartSegments(stream,"demo_h743_001",60000).map(s=>s.map(r=>r.id)),[[20,21],[23]]);
assert.equal(freshness(stream[3],72001,60).fresh,false);
console.log("PASS: 3s window labels/counts, partial failures, insufficient/NA, legacy separation, record-id dedup and failed-window gaps");

const {metricFreshness,shortestAngle,DEFAULT_METRICS}=require("../web/app.js");
assert.equal(Object.keys(DEFAULT_METRICS).length,11);
assert.equal(DEFAULT_METRICS.soil_ph.unit,"");
assert.equal(DEFAULT_METRICS.air_humidity_rh_pct.unit,"%RH");
assert.equal(displayReading({status:"OK",value:null},"soil_ph").valid,false);
assert.equal(displayReading({status:"OK",value:0},"wind_speed_mps").text,"0.00");
assert.equal(displayReading({data:{soil_ph:{status:"OK",value:6}}},"soil_ph").text,"6.00");
assert.equal(metricFreshness({status:"OK",value:19.4,age_ms:30000},DEFAULT_METRICS.temperature_c).valid,true);
assert.equal(metricFreshness({status:"OK",value:19.4,age_ms:30000},DEFAULT_METRICS.temperature_c,1).stale,true);
assert.equal(metricFreshness({status:"OK",value:103.73,age_ms:90000},DEFAULT_METRICS.pressure_kpa).valid,true);
assert.equal(shortestAngle(359,1),361);
assert.equal(uniqueReadings([{id:1,metric:"soil_ph"},{id:1,metric:"wind_speed_mps"}]).length,2);
assert.deepEqual(chartSegments([{id:1,device_id:"d",metric:"wind_direction_deg",value:359,status:"OK",received_at:new Date(1000).toISOString()},{id:2,device_id:"d",metric:"wind_direction_deg",value:1,status:"OK",received_at:new Date(4000).toISOString()}],"d",9000,"wind_direction_deg").map(s=>s.length),[1,1]);
console.log("PASS: ten physical metrics, units, null/zero, independent ages, measurement identity, circular pointer/chart wrap");

